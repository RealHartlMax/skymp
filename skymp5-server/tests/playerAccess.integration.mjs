import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { EventEmitter } from 'node:events';
const require = createRequire(import.meta.url);
const esbuild = require('../node_modules/esbuild');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'skymp-steam-access-'));
const output = process.env.SKYMP_STEAM_UNIT_BUNDLE || path.join(root, 'player-access.cjs');
if (!process.env.SKYMP_STEAM_UNIT_BUNDLE) esbuild.buildSync({ entryPoints: [path.resolve('../skymp5-server/ts/playerAccess.ts')], outfile: output, bundle: true, platform: 'node', target: 'es2022', logLevel: 'silent' });
const api = require(output);
const settings = { dataDir: path.join(root, 'data'), publicHost: 'test.example', port: 7777, playerAccess: { mode: 'guest', approvalRequired: true, steamApiKey: 'a'.repeat(32), steamAppId: 489830 } };
const steamId = '76561198000000000', otherId = '76561198000000001';
const ticket = 'ab'.repeat(128), checks = [];
let calls = 0;
const fetchSteam = async input => {
  calls++;
  const url = new URL(input);
  assert.equal(url.origin, 'https://api.steampowered.com');
  assert.equal(url.searchParams.get('appid'), '489830');
  assert.equal(url.searchParams.get('identity'), api.playerAccessPolicy(settings).ticketIdentity);
  assert.match(url.searchParams.get('identity'), /^skymp[a-f0-9]{24}$/);
  assert.equal(url.searchParams.get('key'), settings.playerAccess.steamApiKey);
  return Response.json({ response: { params: { result: 'OK', steamid: steamId } } });
};
const realNow = Date.now;
let now = realNow();
Date.now = () => now;
try {
  const compactIdentity = api.playerAccessPolicy(settings).ticketIdentity;
  assert.match(compactIdentity, /^skymp[a-f0-9]{24}$/);
  assert.equal(api.playerAccessPolicy({ ...settings }).ticketIdentity, compactIdentity);
  const longPrefix = 'server'.repeat(40);
  assert.notEqual(api.playerAccessPolicy({ ...settings, serverUid: longPrefix + 'a' }).ticketIdentity, api.playerAccessPolicy({ ...settings, serverUid: longPrefix + 'b' }).ticketIdentity);
  await assert.rejects(api.authenticateSteamTicket(settings, ticket, steamId, fetchSteam, 'outdated-policy'), /STEAM_POLICY_CHANGED/);
  assert.equal(calls, 0, 'A stale launcher policy must not reach Valve');
  assert.equal(api.playerAccessPolicy({ offlineMode: true }).mode, 'guest');
  assert.equal(api.validatePlayerAccess({ playerAccess: { mode: 'guest', steamApiKey: 'invalid' } })?.includes('32-character'), true);
  await assert.rejects(api.authenticateSteamTicket({ ...settings, playerAccess: { ...settings.playerAccess, steamApiKey: '' } }, ticket, steamId, fetchSteam), /STEAM_KEY_MISSING/);
  assert.equal(calls, 0);
  for (const invalid of ['', 'zz'.repeat(128), 'a'.repeat(33)]) await assert.rejects(api.authenticateSteamTicket(settings, invalid, steamId, fetchSteam), /STEAM_TICKET_INVALID/);
  await assert.rejects(api.authenticateSteamTicket(settings, ticket, otherId, fetchSteam), /STEAM_TICKET_INVALID/);
  for (const invalid of ['a'.repeat(33), '<name>', 'admin\nname', 'test\u202ename', 42, {}]) {
    const before = calls;
    await assert.rejects(api.authenticateSteamTicket(settings, 'fe'.repeat(128), steamId, fetchSteam, undefined, invalid), /PLAYER_NAME_INVALID/);
    assert.equal(calls, before, 'Invalid names must not reach Valve');
  }
  const auth = await api.authenticateSteamTicket(settings, ticket, steamId, fetchSteam, undefined, '  Hüter ÄÖÜ Довакин  ');
  assert.equal(auth.playerName, 'Hüter ÄÖÜ Довакин');
  const profileBeforeRename = api.listPlayerAccess(settings)[0].profileId;
  assert.equal(auth.steamId, steamId); assert.equal(auth.status, 'pending'); assert.equal(auth.accountLoginRequired, false);
  const beforeReplay = calls;
  await assert.rejects(api.authenticateSteamTicket(settings, ticket, steamId, fetchSteam), /STEAM_TICKET_REPLAY/);
  assert.equal(calls, beforeReplay);
  const disk = fs.readFileSync(path.join(settings.dataDir, 'player-access.json'), 'utf8');
  for (const secret of [auth.steamSession, ticket, settings.playerAccess.steamApiKey]) assert(!disk.includes(secret));
  checks.push('Valve result determines SteamID; missing key, forged ID, malformed/replayed tickets are rejected; private credentials and raw sessions are not stored');

  const packets = [], allowed = [], connected = new Set([1, 2, 3]);
  const guids = new Map([[1, 'guid-1'], [2, 'guid-2'], [3, 'guid-3']]);
  const ctx = { svr: { getUserGuid: id => guids.get(id), isConnected: id => connected.has(id), sendCustomPacket: (id, payload) => packets.push({ userId: id, ...JSON.parse(payload) }) }, gm: new EventEmitter() };
  const sessions = new api.SteamPlayerSessions(() => settings, (ctx, userId, profileId) => allowed.push({ userId, profileId }));
  assert.equal(sessions.handle(1, 'loginWithSteam', { steamSession: '0'.repeat(64), steamId, profileId: 42 }, ctx), true);
  assert.equal(allowed.length, 0); assert.equal(packets.at(-1).state, 'error');
  sessions.handle(1, 'loginWithSteam', { steamSession: auth.steamSession, steamId: otherId, profileId: 42 }, ctx);
  assert.equal(packets.at(-1).state, 'pending'); assert.equal(allowed.length, 0);
  assert.deepEqual(api.getSteamPlayerInfo(ctx.svr, 1), { steamId, playerName: 'Hüter ÄÖÜ Довакин' });
  const renamed = await api.authenticateSteamTicket(settings, 'fa'.repeat(128), steamId, fetchSteam, undefined, 'Neuer Name');
  assert.equal(renamed.playerName, 'Neuer Name');
  assert.equal(api.listPlayerAccess(settings)[0].profileId, profileBeforeRename);
  assert.equal(api.listPlayerAccess(settings)[0].status, 'pending');
  assert.equal(api.getSteamPlayerInfo(ctx.svr, 1).playerName, 'Hüter ÄÖÜ Довакин', 'A new preflight cannot rename an active session');
  checks.push('Unicode names bind to verified sessions; renaming preserves profile and approval; forged game-packet names cannot override display names');
  api.changePlayerAccess(settings, 'steam:' + steamId, 'approve'); now += 2000;
  sessions.handle(1, 'steamLoginStatus', {}, ctx);
  assert.equal(allowed.length, 1); assert.equal(allowed[0].profileId, 2000000000);
  assert.equal(sessions.getSteamId(ctx, 1), steamId);
  sessions.handle(2, 'loginWithSteam', { steamSession: auth.steamSession }, ctx);
  assert.equal(packets.at(-1).state, 'duplicate'); assert.equal(allowed.length, 1);
  sessions.disconnect(1); assert.deepEqual(api.getSteamPlayerInfo(ctx.svr, 1), {}); connected.delete(1); now += 2000;
  sessions.handle(2, 'steamLoginStatus', {}, ctx); assert.equal(allowed.length, 2);
  guids.set(2, 'new-guid'); assert.equal(sessions.getSteamId(ctx, 2), undefined);
  checks.push('No client-chosen Steam/profile identity; pending guests cannot spawn; dashboard approval unlocks the assigned profile; duplicate Steam sessions are refused and disconnect permits reconnect');

  api.changePlayerAccess(settings, 'steam:' + steamId, 'block');
  sessions.handle(3, 'loginWithSteam', { steamSession: auth.steamSession }, ctx); assert.equal(packets.at(-1).state, 'blocked');
  assert.equal(sessions.getSteamId(ctx, 3), undefined); assert.deepEqual(api.getSteamPlayerInfo(ctx.svr, 3), {});
  assert.equal(sessions.claim(ctx, 3), false, 'A blocked Steam identity cannot bypass the denial with a master-login packet');
  api.changePlayerAccess(settings, 'steam:' + steamId, 'approve');
  settings.playerAccess.mode = 'account'; now += 2000;
  sessions.handle(3, 'steamLoginStatus', {}, ctx); assert.equal(packets.at(-1).customPacketType, 'playerAccountRequired');
  api.bindSteamAccount(settings, 'https://api.skymp-worlds.net', 42, steamId);
  assert.throws(() => api.bindSteamAccount(settings, 'https://api.skymp-worlds.net', 42, otherId), /another Steam identity/);
  api.bindSteamAccount(settings, 'https://gateway.skymp.net', 42, otherId);
  now += 9 * 60 * 60 * 1000;
  assert.equal(sessions.getSteamId(ctx, 3), undefined);
  assert.equal(sessions.claim(ctx, 3), false, 'A master response arriving after Steam session expiry cannot authorize a spawn');
  sessions.handle(3, 'steamLoginStatus', {}, ctx); assert.equal(packets.at(-1).state, 'error');
  checks.push('Steam blocks apply independently of account provider; master accounts bind to one Steam identity; expired sessions cannot log in');
  Date.now = realNow;
  const Koa = require('koa'), Router = require('koa-router'), body = require('koa-body');
  const app = new Koa(), router = new Router();
  app.use(body({ jsonLimit: '32kb' }));
  api.registerPlayerAccess(router, { settings: () => settings, fetch: fetchSteam,
    authorize: ctx => { if (ctx.get('X-Test-Admin') === 'yes') return true; ctx.status = 401; return false; } });
  app.use(router.routes());
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  const base = 'http://127.0.0.1:' + server.address().port;
  try {
    const policy = await (await fetch(base + '/api/launcher/auth-policy')).json();
    assert.equal(policy.version, 2); assert.equal(policy.ticketIdentity, compactIdentity);
    assert.equal(policy.steamRequired, true); assert.equal(policy.accountLoginRequired, true);
    assert(!JSON.stringify(policy).includes(settings.playerAccess.steamApiKey));
    assert.equal((await fetch(base + '/api/admin/player-access')).status, 401);
    const headers = { 'Content-Type': 'application/json', 'X-Test-Admin': 'yes' };
    const change = { id: 'steam:' + steamId, action: 'approve' };
    assert.equal((await fetch(base + '/api/admin/player-access', { method: 'POST', headers, body: JSON.stringify(change) })).status, 403);
    assert.equal((await fetch(base + '/api/admin/player-access', { method: 'POST', headers: { ...headers, Origin: 'https://other.example' }, body: JSON.stringify(change) })).status, 403);
    assert.equal((await fetch(base + '/api/admin/player-access', { method: 'POST', headers: { ...headers, Origin: base }, body: JSON.stringify(change) })).status, 200);
    const callsBeforePolicyChange = calls;
    const changed = await fetch(base + '/api/launcher/auth/steam', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ steamId, ticket: 'de'.repeat(128), ticketIdentity: 'outdated-policy' }) });
    assert.equal(changed.status, 409); assert.equal((await changed.json()).code, 'STEAM_POLICY_CHANGED'); assert.equal(calls, callsBeforePolicyChange);
    const matchingPolicy = await fetch(base + '/api/launcher/auth/steam', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ steamId, ticket: 'ef'.repeat(128), ticketIdentity: policy.ticketIdentity }) });
    assert.equal(matchingPolicy.status, 200); assert.equal((await matchingPolicy.json()).steamId, steamId);
    const invalidName = await fetch(base + '/api/launcher/auth/steam', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ steamId, ticket: 'fb'.repeat(128), playerName: '<spoof>' }) });
    assert.equal(invalidName.status, 400); assert.equal((await invalidName.json()).code, 'PLAYER_NAME_INVALID');
    const accepted = await fetch(base + '/api/launcher/auth/steam', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ steamId, ticket: 'cd'.repeat(128) }) });
    assert.equal(accepted.status, 200); assert.equal((await accepted.json()).steamId, steamId);
    const replay = await fetch(base + '/api/launcher/auth/steam', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ steamId, ticket: 'cd'.repeat(128) }) });
    assert.equal(replay.status, 401);
    checks.push('Compact server-bound policy is stable and distinguishes long instance IDs; HTTP policy v2 accepts matching identity and omitted legacy echo, rejects stale echo before Valve');
    let last;
    for (let i = 0; i < 30; i++) last = await fetch(base + '/api/launcher/auth/steam', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' });
    assert.equal(last.status, 429);
    checks.push('Real loopback HTTP routes hide keys, protect admin reads/writes and Origin, issue verified sessions, reject replay and rate-limit repeated ticket attempts');
  } finally { await new Promise(resolve => server.close(resolve)); }
  console.log(JSON.stringify({ ok: true, checks, realSteamContacted: false, skyrimStarted: false }));
} finally {
  Date.now = realNow;
  assert.equal(path.dirname(root), path.resolve(os.tmpdir()));
  assert(path.basename(root).startsWith('skymp-steam-access-'));
  fs.rmSync(root, { recursive: true, force: true });
}
